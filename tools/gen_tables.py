"""Generate core/generated_tables.inc from the TFLite schema and kernel sources.

Usage: python -I tools/gen_tables.py <schema.fbs> <kernel_map.txt> > core/generated_tables.inc

schema.fbs comes from tensorflow/compiler/mlir/lite/schema/schema.fbs (Apache-2.0).
kernel_map.txt lists, for each tensorflow/lite/kernels/*.cc file, the Register_* functions it
defines (one line: "<file> OP OP ..."). Both are inputs only; the output is plain C++ tables.
"""
import re
import sys


def enum_body(src: str, name: str) -> list[tuple[str, int]]:
    m = re.search(r"enum\s+" + name + r"\s*:\s*\w+\s*\{(.*?)\}", src, re.S)
    if not m:
        raise SystemExit(f"enum {name} not found")
    out = []
    for line in m.group(1).splitlines():
        line = line.split("//")[0].strip()
        mm = re.match(r"([A-Z0-9_]+)\s*=\s*(-?\d+)", line)
        if mm:
            out.append((mm.group(1), int(mm.group(2))))
    return out


def main() -> None:
    schema = open(sys.argv[1], encoding="utf-8").read()
    kmap = [l.split() for l in open(sys.argv[2], encoding="utf-8") if l.strip()]
    ops = enum_body(schema, "BuiltinOperator")
    types = enum_body(schema, "TensorType")
    op_names = {n for n, _ in ops}

    print("// Generated by tools/gen_tables.py from the TensorFlow Lite schema (Apache-2.0).")
    print("// Do not edit by hand.")
    print("#pragma once")
    print("namespace tl::gen {")
    print("struct OpName { int code; const char *name; };")
    print("static const OpName kBuiltinOps[] = {")
    for n, v in ops:
        print(f'  {{ {v}, "{n}" }},')
    print("};")
    print("static const OpName kTensorTypes[] = {")
    for n, v in types:
        print(f'  {{ {v}, "{n}" }},')
    print("};")
    print("// Kernel source file -> builtin operators it implements (variants such as _REF/_OPT")
    print("// folded into their base op where the base op exists).")
    print("struct KernelFile { const char *file; const char *ops; };")
    print("static const KernelFile kKernelFiles[] = {")
    for row in kmap:
        f, regs = row[0], row[1:]
        base = []
        for r in regs:
            b = r
            if b not in op_names:
                # strip variant suffixes: CONV_2D_UINT8, ADD_REF, TANH_GENERIC_OPT ...
                for suf in ("_GENERIC_OPT_UINT8", "_GENERIC_OPT", "_FIXED_POINT_OPT", "_MULTITHREADED_OPT",
                            "_CBLAS_OPT", "_NEON_OPT", "_REF", "_OPT", "_UINT8", "_INT8", "_INT16", "_FLOAT"):
                    if b.endswith(suf) and b[: -len(suf)] in op_names:
                        b = b[: -len(suf)]
                        break
            if b in op_names and b not in base:
                base.append(b)
        if base:
            print(f'  {{ "{f}", "{" ".join(base)}" }},')
    print("};")
    print("}  // namespace tl::gen")


if __name__ == "__main__":
    main()
